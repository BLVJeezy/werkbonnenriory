export type IbanBank = { bic: string | null; bank: string | null };

const NONE: IbanBank = { bic: null, bank: null };

/** Pure: finds the bank behind an IBAN from the bank code inside it — Belgium and the Netherlands. */
export function bankOfIban(iban: string | null | undefined): IbanBank {
  const s = (iban ?? "").toUpperCase().replace(/[\s-]/g, "");
  if (s.startsWith("BE")) {
    const code = s.slice(4, 7);
    if (!/^\d{3}$/.test(code)) return NONE;
    const hit = BE.find(([from, to]) => code >= from && code <= to);
    return hit ? { bic: hit[2], bank: hit[3] } : NONE;
  }
  if (s.startsWith("NL")) {
    const id = s.slice(4, 8);
    if (!/^[A-Z]{4}$/.test(id)) return NONE;
    const hit = NL[id];
    return hit ? { bic: hit[0], bank: hit[1] } : NONE;
  }
  return NONE;
}

/** Pure: the BIC that belongs to an IBAN, or null when the bank is not in the list. */
export function bicFromIban(iban: string | null | undefined): string | null {
  return bankOfIban(iban).bic;
}
